"""
analyse_assignment_synthetic.py

Analyse the frozen Synthetic FINAL controlled experiments for the
one-to-one plane correspondence Assignment stage.

This script does NOT rerun or retune any algorithm.

It analyses:
    1. Overall assignment accuracy
    2. Normal-case performance
    3. Hard / ambiguous-case robustness
    4. Unmatched / unequal-plane handling
    5. Runtime
    6. Objective-cost agreement between solvers

Expected input
--------------
results/assignment/synthetic_final/per_case_results.csv

Outputs
-------
results/assignment/synthetic_final/analysis/
    overall_comparison.csv
    by_scenario.csv
    runtime_comparison.csv
    solver_agreement.csv
    controlled_experiment_summary.csv
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

import numpy as np


# ============================================================
# Configuration
# ============================================================

ALGORITHMS = [
    "hungarian",
    "auction",
    "jonker_volgenant",
    "cost_scaling",
]

SCENARIOS = [
    "normal",
    "hard",
    "unmatched",
]


# ============================================================
# CSV loading
# ============================================================

def load_results(
    path: Path,
) -> list[dict]:
    """
    Load per-case results generated by run_assignment_synthetic.py.
    """

    if not path.exists():
        raise FileNotFoundError(
            f"Result file not found:\n{path}"
        )

    with path.open(
        "r",
        encoding="utf-8",
        newline="",
    ) as f:

        rows = list(
            csv.DictReader(f)
        )

    if not rows:
        raise ValueError(
            f"No result rows found in {path}"
        )

    print(
        f"Loaded {len(rows)} "
        f"algorithm-case results."
    )

    return rows


# ============================================================
# Helpers
# ============================================================

def _float(
    row: dict,
    key: str,
    default: float = 0.0,
) -> float:
    """
    Safely read a numerical CSV field.
    """

    value = row.get(
        key,
        "",
    )

    if value in (
        "",
        None,
    ):
        return default

    return float(value)


def _mean(
    values: list[float],
) -> float:

    if not values:
        return 0.0

    return float(
        np.mean(values)
    )


def _median(
    values: list[float],
) -> float:

    if not values:
        return 0.0

    return float(
        np.median(values)
    )


def _p95(
    values: list[float],
) -> float:

    if not values:
        return 0.0

    return float(
        np.percentile(
            values,
            95,
        )
    )


def _std(
    values: list[float],
) -> float:

    if not values:
        return 0.0

    return float(
        np.std(values)
    )


# ============================================================
# Core aggregation
# ============================================================

def summarise_rows(
    rows: list[dict],
) -> dict:
    """
    Summarise a collection of per-case Assignment results.

    Metrics are macro-averaged across cases.
    """

    if not rows:
        raise ValueError(
            "Cannot summarise an empty row set"
        )

    precision = [
        _float(row, "precision")
        for row in rows
    ]

    recall = [
        _float(row, "recall")
        for row in rows
    ]

    f1 = [
        _float(row, "f1")
        for row in rows
    ]

    unmatched_f1 = [
        _float(
            row,
            "unmatched_f1",
        )
        for row in rows
    ]

    ffmr = [
        _float(row, "ffmr")
        for row in rows
    ]

    exact = [
        _float(
            row,
            "exact_assignment",
        )
        for row in rows
    ]

    runtime = [
        _float(
            row,
            "runtime_ms",
        )
        for row in rows
    ]

    return {
        "n_cases":
            len(rows),

        "precision_mean":
            _mean(precision),

        "recall_mean":
            _mean(recall),

        "f1_mean":
            _mean(f1),

        "f1_std":
            _std(f1),

        "exact_assignment_rate":
            _mean(exact),

        "unmatched_f1_mean":
            _mean(
                unmatched_f1
            ),

        "ffmr_mean":
            _mean(ffmr),

        "runtime_mean_ms":
            _mean(runtime),

        "runtime_median_ms":
            _median(runtime),

        "runtime_p95_ms":
            _p95(runtime),

        "runtime_std_ms":
            _std(runtime),
    }


# ============================================================
# Overall comparison
# ============================================================

def build_overall_comparison(
    rows: list[dict],
) -> list[dict]:
    """
    Aggregate all Synthetic FINAL cases for each algorithm.
    """

    output = []

    for algorithm in ALGORITHMS:

        selected = [
            row
            for row in rows
            if row["algorithm"]
            == algorithm
        ]

        if not selected:
            continue

        summary = summarise_rows(
            selected
        )

        output.append(
            {
                "algorithm":
                    algorithm,

                **summary,
            }
        )

    return output


# ============================================================
# Scenario comparison
# ============================================================

def build_scenario_comparison(
    rows: list[dict],
) -> list[dict]:
    """
    Summarise normal, hard and unmatched controlled experiments.
    """

    output = []

    for algorithm in ALGORITHMS:

        for scenario in SCENARIOS:

            selected = [
                row
                for row in rows
                if (
                    row["algorithm"]
                    == algorithm

                    and row["scenario"]
                    == scenario
                )
            ]

            if not selected:
                continue

            summary = summarise_rows(
                selected
            )

            output.append(
                {
                    "algorithm":
                        algorithm,

                    "scenario":
                        scenario,

                    **summary,
                }
            )

    return output


# ============================================================
# Runtime comparison
# ============================================================

def build_runtime_comparison(
    rows: list[dict],
) -> list[dict]:
    """
    Produce dedicated runtime statistics.
    """

    output = []

    for algorithm in ALGORITHMS:

        selected = [
            row
            for row in rows
            if row["algorithm"]
            == algorithm
        ]

        if not selected:
            continue

        runtime = [
            _float(
                row,
                "runtime_ms",
            )
            for row in selected
        ]

        output.append(
            {
                "algorithm":
                    algorithm,

                "n_cases":
                    len(runtime),

                "runtime_mean_ms":
                    _mean(runtime),

                "runtime_median_ms":
                    _median(runtime),

                "runtime_p95_ms":
                    _p95(runtime),

                "runtime_std_ms":
                    _std(runtime),

                "runtime_min_ms":
                    float(
                        np.min(runtime)
                    ),

                "runtime_max_ms":
                    float(
                        np.max(runtime)
                    ),
            }
        )

    return output


# ============================================================
# Solver agreement
# ============================================================

def build_solver_agreement(
    rows: list[dict],
    cost_tolerance: float,
) -> list[dict]:
    """
    Compare objective costs obtained by the four solvers.

    Hungarian, Jonker-Volgenant and Cost-Scaling are treated as the
    exact/reference group.

    Because the current per-case result file does not store the complete
    correspondence set, agreement is assessed using total augmented
    objective cost rather than exact match-set equality.

    Auction is compared against the best exact-solver cost.
    """

    by_case: dict[str, dict[str, dict]] = {}

    for row in rows:

        case_id = row["case_id"]
        algorithm = row["algorithm"]

        by_case.setdefault(
            case_id,
            {},
        )

        by_case[
            case_id
        ][
            algorithm
        ] = row

    output = []

    exact_algorithms = [
        "hungarian",
        "jonker_volgenant",
        "cost_scaling",
    ]

    for case_id, algorithms in sorted(
        by_case.items()
    ):

        if not all(
            name in algorithms
            for name in ALGORITHMS
        ):
            continue

        scenario = algorithms[
            "hungarian"
        ][
            "scenario"
        ]

        costs = {
            name:
                _float(
                    algorithms[name],
                    "total_augmented_cost",
                )
            for name in ALGORITHMS
        }

        f1_scores = {
            name:
                _float(
                    algorithms[name],
                    "f1",
                )
            for name in ALGORITHMS
        }

        exact_costs = [
            costs[name]
            for name in exact_algorithms
        ]

        exact_cost_min = min(
            exact_costs
        )

        exact_cost_max = max(
            exact_costs
        )

        exact_cost_spread = (
            exact_cost_max
            - exact_cost_min
        )

        exact_cost_agreement = int(
            exact_cost_spread
            <= cost_tolerance
        )

        auction_gap = (
            costs["auction"]
            - exact_cost_min
        )

        denominator = max(
            abs(exact_cost_min),
            1e-12,
        )

        auction_relative_gap = (
            auction_gap
            / denominator
        )

        exact_f1_values = [
            f1_scores[name]
            for name in exact_algorithms
        ]

        exact_f1_spread = (
            max(exact_f1_values)
            - min(exact_f1_values)
        )

        output.append(
            {
                "case_id":
                    case_id,

                "scenario":
                    scenario,

                "hungarian_cost":
                    costs[
                        "hungarian"
                    ],

                "jonker_volgenant_cost":
                    costs[
                        "jonker_volgenant"
                    ],

                "cost_scaling_cost":
                    costs[
                        "cost_scaling"
                    ],

                "auction_cost":
                    costs[
                        "auction"
                    ],

                "exact_cost_spread":
                    exact_cost_spread,

                "exact_cost_agreement":
                    exact_cost_agreement,

                "auction_absolute_gap":
                    auction_gap,

                "auction_relative_gap":
                    auction_relative_gap,

                "exact_f1_spread":
                    exact_f1_spread,

                "hungarian_f1":
                    f1_scores[
                        "hungarian"
                    ],

                "jonker_volgenant_f1":
                    f1_scores[
                        "jonker_volgenant"
                    ],

                "cost_scaling_f1":
                    f1_scores[
                        "cost_scaling"
                    ],

                "auction_f1":
                    f1_scores[
                        "auction"
                    ],
            }
        )

    return output


# ============================================================
# Controlled-experiment report table
# ============================================================

def _find_scenario(
    scenario_rows: list[dict],
    algorithm: str,
    scenario: str,
) -> dict:

    for row in scenario_rows:

        if (
            row["algorithm"]
            == algorithm

            and row["scenario"]
            == scenario
        ):
            return row

    raise KeyError(
        f"Missing scenario result: "
        f"{algorithm}, {scenario}"
    )


def _find_overall(
    overall_rows: list[dict],
    algorithm: str,
) -> dict:

    for row in overall_rows:

        if row["algorithm"] == algorithm:
            return row

    raise KeyError(
        f"Missing overall result: {algorithm}"
    )


def build_controlled_summary(
    overall_rows: list[dict],
    scenario_rows: list[dict],
) -> list[dict]:
    """
    Produce one compact report-ready evidence row per algorithm.

    The principal metrics correspond directly to the planned
    Assignment evaluation criteria.
    """

    output = []

    for algorithm in ALGORITHMS:

        overall = _find_overall(
            overall_rows,
            algorithm,
        )

        normal = _find_scenario(
            scenario_rows,
            algorithm,
            "normal",
        )

        hard = _find_scenario(
            scenario_rows,
            algorithm,
            "hard",
        )

        unmatched = _find_scenario(
            scenario_rows,
            algorithm,
            "unmatched",
        )

        output.append(
            {
                "algorithm":
                    algorithm,

                # --------------------------------------------
                # Assignment Accuracy
                # --------------------------------------------

                "F1_overall":
                    overall[
                        "f1_mean"
                    ],

                "precision_overall":
                    overall[
                        "precision_mean"
                    ],

                "recall_overall":
                    overall[
                        "recall_mean"
                    ],

                "exact_assignment_rate":
                    overall[
                        "exact_assignment_rate"
                    ],

                # --------------------------------------------
                # Controlled Normal experiment
                # --------------------------------------------

                "F1_normal":
                    normal[
                        "f1_mean"
                    ],

                # --------------------------------------------
                # Robustness
                # --------------------------------------------

                "F1_hard":
                    hard[
                        "f1_mean"
                    ],

                # --------------------------------------------
                # Unmatched / unequal handling
                # --------------------------------------------

                "F1_unmatched_correspondence":
                    unmatched[
                        "f1_mean"
                    ],

                "F1_unmatched_plane":
                    unmatched[
                        "unmatched_f1_mean"
                    ],

                "FFMR_unmatched":
                    unmatched[
                        "ffmr_mean"
                    ],

                # --------------------------------------------
                # Processing speed
                # --------------------------------------------

                "runtime_mean_ms":
                    overall[
                        "runtime_mean_ms"
                    ],

                "runtime_median_ms":
                    overall[
                        "runtime_median_ms"
                    ],

                "runtime_p95_ms":
                    overall[
                        "runtime_p95_ms"
                    ],
            }
        )

    return output


# ============================================================
# CSV writer
# ============================================================

def save_csv(
    path: Path,
    rows: list[dict],
) -> None:

    if not rows:
        raise ValueError(
            f"No rows available for {path}"
        )

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    fieldnames = []

    seen = set()

    for row in rows:

        for key in row:

            if key not in seen:

                seen.add(key)

                fieldnames.append(key)

    with path.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as f:

        writer = csv.DictWriter(
            f,
            fieldnames=fieldnames,
        )

        writer.writeheader()

        writer.writerows(
            rows
        )


# ============================================================
# Console summary
# ============================================================

def print_controlled_summary(
    rows: list[dict],
) -> None:

    print(
        "\n"
        "===================================================================="
    )

    print(
        "ASSIGNMENT CONTROLLED EXPERIMENT SUMMARY"
    )

    print(
        "===================================================================="
    )

    print(
        f"{'Algorithm':<20}"
        f"{'Overall':>9}"
        f"{'Normal':>9}"
        f"{'Hard':>9}"
        f"{'Unmatch':>10}"
        f"{'FFMR':>9}"
        f"{'Mean ms':>10}"
    )

    print(
        "-" * 76
    )

    for row in rows:

        print(
            f"{row['algorithm']:<20}"
            f"{row['F1_overall']:>9.4f}"
            f"{row['F1_normal']:>9.4f}"
            f"{row['F1_hard']:>9.4f}"
            f"{row['F1_unmatched_plane']:>10.4f}"
            f"{row['FFMR_unmatched']:>9.4f}"
            f"{row['runtime_mean_ms']:>10.4f}"
        )


def print_agreement_summary(
    rows: list[dict],
) -> None:

    if not rows:
        return

    agreement_rate = _mean(
        [
            float(
                row[
                    "exact_cost_agreement"
                ]
            )
            for row in rows
        ]
    )

    auction_abs_gap = _mean(
        [
            abs(
                float(
                    row[
                        "auction_absolute_gap"
                    ]
                )
            )
            for row in rows
        ]
    )

    exact_f1_spread = _mean(
        [
            float(
                row[
                    "exact_f1_spread"
                ]
            )
            for row in rows
        ]
    )

    print(
        "\nSolver consistency:"
    )

    print(
        f"  Exact-solver objective agreement: "
        f"{agreement_rate * 100:.2f}%"
    )

    print(
        f"  Mean |Auction cost gap|: "
        f"{auction_abs_gap:.8f}"
    )

    print(
        f"  Mean exact-solver F1 spread: "
        f"{exact_f1_spread:.8f}"
    )


# ============================================================
# Main
# ============================================================

def main() -> None:

    parser = argparse.ArgumentParser(
        description=(
            "Analyse Synthetic FINAL controlled "
            "Assignment experiments."
        )
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=Path(
            "results/assignment/"
            "synthetic_final/"
            "per_case_results.csv"
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(
            "results/assignment/"
            "synthetic_final/"
            "analysis"
        ),
    )

    parser.add_argument(
        "--cost-tolerance",
        type=float,
        default=1e-6,
        help=(
            "Tolerance used when comparing objective costs "
            "from exact/reference solvers."
        ),
    )

    args = parser.parse_args()

    if args.cost_tolerance < 0:
        raise ValueError(
            "--cost-tolerance must be non-negative"
        )

    # --------------------------------------------------------
    # Load frozen Synthetic FINAL results
    # --------------------------------------------------------

    rows = load_results(
        args.input
    )

    # --------------------------------------------------------
    # Basic checks
    # --------------------------------------------------------

    algorithms_present = {
        row["algorithm"]
        for row in rows
    }

    scenarios_present = {
        row["scenario"]
        for row in rows
    }

    missing_algorithms = [
        algorithm
        for algorithm in ALGORITHMS
        if algorithm
        not in algorithms_present
    ]

    missing_scenarios = [
        scenario
        for scenario in SCENARIOS
        if scenario
        not in scenarios_present
    ]

    if missing_algorithms:

        raise ValueError(
            "Missing algorithms in result file: "
            + ", ".join(
                missing_algorithms
            )
        )

    if missing_scenarios:

        raise ValueError(
            "Missing controlled scenarios: "
            + ", ".join(
                missing_scenarios
            )
        )

    # --------------------------------------------------------
    # Analysis
    # --------------------------------------------------------

    overall_rows = (
        build_overall_comparison(
            rows
        )
    )

    scenario_rows = (
        build_scenario_comparison(
            rows
        )
    )

    runtime_rows = (
        build_runtime_comparison(
            rows
        )
    )

    agreement_rows = (
        build_solver_agreement(
            rows,
            cost_tolerance=
                args.cost_tolerance,
        )
    )

    controlled_rows = (
        build_controlled_summary(
            overall_rows,
            scenario_rows,
        )
    )

    # --------------------------------------------------------
    # Save outputs
    # --------------------------------------------------------

    args.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    save_csv(
        args.output_dir
        / "overall_comparison.csv",
        overall_rows,
    )

    save_csv(
        args.output_dir
        / "by_scenario.csv",
        scenario_rows,
    )

    save_csv(
        args.output_dir
        / "runtime_comparison.csv",
        runtime_rows,
    )

    save_csv(
        args.output_dir
        / "solver_agreement.csv",
        agreement_rows,
    )

    save_csv(
        args.output_dir
        / "controlled_experiment_summary.csv",
        controlled_rows,
    )

    # --------------------------------------------------------
    # Console summary
    # --------------------------------------------------------

    print_controlled_summary(
        controlled_rows
    )

    print_agreement_summary(
        agreement_rows
    )

    print(
        "\nAnalysis files saved to:"
    )

    print(
        f"  {args.output_dir}"
    )

    print(
        "\nSynthetic controlled-experiment "
        "analysis complete."
    )


if __name__ == "__main__":
    main()